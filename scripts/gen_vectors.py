"""Regenerate tests/protocol-vectors.json from explicit inputs.

The vectors pin the codec behaviour that the browser (web/v1/protocol.mjs) and Home
Assistant (ble_protocol.py) must share. Both test suites check every case. Only
regenerate after an intentional protocol change, and review the diff: a vector that
changes means both implementations must change with it.

    python scripts/gen_vectors.py
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from custom_components.coway_local.ble_protocol import (  # noqa: E402
    FAILURE_CODES,
    STATUS,
    advertised_product,
    encode_proto,
    fragments,
)


def scan_item(ssid, bssid, rssi, security, channel):
    raw = ssid.encode()
    return (
        b"\0\0"
        + len(raw).to_bytes(2, "little")
        + raw.ljust(32, b"\0")
        + bytes.fromhex(bssid)
        + rssi.to_bytes(4, "little", signed=True)
        + bytes([security, channel])
    )


NETWORKS = [
    ("Home", "aabbccddeeff", -41, 4, 6),
    ("Open café", "001122334455", -77, 0, 11),
    ("Five", "0a0b0c0d0e0f", -30, 4, 36),
    ("", "000000000001", -90, 0, 1),
]
CAPTURED = "0016313133343339303030303030303030303030303030c5"

proto = [
    {"fields": {"1": 300, "2": "text"}},
    {"fields": {"1": 2, "3": "", "5": 0, "14": "LOCAL0001122334455"}},
    {"fields": {"1": 1, "2": "YWJjZGVmZ2hpamtsbW5vcHFyc3Q="}},
    {"fields": {"1": 2, "2": 1, "3": 61}},
    {"fields": {"16": 16384, "2": "Purifier · 空气"}},
]
for case in proto:
    fields = {int(k): v for k, v in case["fields"].items()}
    case["hex"] = encode_proto(fields).hex()
    # Decoding returns only nonzero/nonempty fields, strings as UTF-8 bytes.
    case["decoded"] = {
        k: (v if isinstance(v, int) else v.encode().hex())
        for k, v in case["fields"].items()
        if v not in (0, "")
    }

messages = [b"x", b"a" * 16, b"a" * 17, bytes(range(256)) * 2]
frag = []
for size in (20, 23, 185):
    for message in messages:
        frag.append(
            {
                "message": message.hex(),
                "value_size": size,
                "packets": [p.hex() for p in fragments(message, size)],
            }
        )

scan_hex = (
    b"*ICT*SCANRESULT:" + b"".join(scan_item(*n) for n in NETWORKS) + b"[OK]".ljust(48, b"\0")
).hex()

ads = [
    {"company": 0xFFFF, "payload": CAPTURED, "note": "captured AP-1022K"},
    {"company": 0xFFFF, "payload": "0000" + b"999999".hex() + "00", "note": "other text code"},
    {"company": 0xFFFF, "payload": "000040" + b"ZZZZZ".hex(), "note": "base-36 code"},
    {"company": 0xFFFF, "payload": CAPTURED[:14], "note": "7 bytes, too short"},
    {"company": 0xFFFF, "payload": "0000ff00ff00ff00", "note": "not printable"},
    {"company": 0x0639, "payload": "0040" + b"00001".hex(), "note": "newer layout"},
    {"company": 0x0639, "payload": "0041" + b"00001".hex(), "note": "byte 1 is not 0x40"},
    {"company": 0x0639, "payload": "0040" + b"0000".hex(), "note": "6 bytes, too short"},
    {"company": 0x004C, "payload": CAPTURED, "note": "unrelated company"},
]
for ad in ads:
    payload = bytes.fromhex(ad["payload"])
    ad["product"] = advertised_product({ad["company"]: payload})
    # Chrome's manufacturerData filters check the company, length and 0x0639's 0x40
    # byte only; IoCare's stricter code parsing happens in Python after discovery.
    if ad["company"] == 0xFFFF:
        ad["browser_filter"] = len(payload) >= 8
    elif ad["company"] == 0x0639:
        ad["browser_filter"] = len(payload) >= 7 and payload[1] == 0x40
    else:
        ad["browser_filter"] = False

vectors = {
    "$comment": "Generated by scripts/gen_vectors.py; checked by tests/web.test.mjs and "
    "tests/test_ble_protocol.py.",
    "proto": proto,
    "proto_invalid": ["12ff", "08010801", "0b", "0001", "08ffffffffffffffffff01", "1205616263"],
    "fragments": frag,
    "reassembly_invalid": [
        ["020002006161"],
        ["0200010061", "0200010061"],
        ["0300010061", "0200020062"],
        ["000001006161"],
        ["616263"],
    ],
    "scan": {
        "hex": scan_hex,
        "networks": [
            {"ssid": s, "bssid": b, "rssi": r, "security": sec, "channel": c}
            for s, b, r, sec, c in NETWORKS
        ],
        "usable": ["Home", "Open café"],
    },
    "scan_invalid": ["", b"*ICT*SCANRESULX:".hex()],
    "advertisements": ads,
    "identity": [
        {
            "advertised": "AP-1022K_334455",
            "fields": {"1": "COWAY334455", "2": "00:11:22:33:44:55"},
            "expect": {"name": "AP-1022K_334455", "mac": "001122334455", "module": "COWAY334455"},
        },
        {
            "advertised": "",
            "fields": {"1": "COWAY334455", "2": "aabbccddeeff"},
            "expect": {"name": "COWAY334455", "mac": "AABBCCDDEEFF", "module": "COWAY334455"},
        },
        {
            "advertised": None,
            "fields": {"2": "001122334455"},
            "expect": {"name": "Unnamed device", "mac": "001122334455", "module": ""},
        },
    ],
    "identity_invalid": [
        {},
        {"2": "not a MAC"},
        {"2": "0011223344"},
        {"1": 5, "2": "001122334455"},
    ],
    "status": [
        {"code": c, "failure": c in FAILURE_CODES, "description": STATUS.get(c)}
        for c in (0, 2, 10, 50, 51, 52, 61, 72, 73, 99)
    ],
}
path = ROOT / "tests" / "protocol-vectors.json"
path.write_text(json.dumps(vectors, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
print(path.relative_to(ROOT))
